"""Build config.twin.yaml from the Twin team's sensor inventory (their src/city_live/data/sensors.json).
Usage:  python tools/make_twin_config.py partners/twin/sensors.json > config.twin.yaml
Re-run it whenever the Twin team changes its inventory: it fills the device registry (security.registry.allowed_ids)
and the value limits per sensor type from their hard limits."""
import json
import sys
from collections import defaultdict

# per-type tuning that the inventory does not give: fastest believable change per second, noise, frozen window, pair tolerance
TUNING = {
    "water_level":   dict(max_rate=20, frozen_window=5, pair_tol=40),
    "flow":          dict(max_rate=60, frozen_window=8, pair_tol=60),
    "pressure":      dict(max_rate=1.5, frozen_window=8, pair_tol=2),
    "temperature":   dict(max_rate=8, frozen_window=8, pair_tol=10),
    "traffic_count": dict(max_rate=15, frozen_window=10, pair_tol=30),
}


def main(path: str) -> None:
    inv = json.load(open(path, encoding="utf-8"))
    limits = defaultdict(lambda: [float("inf"), float("-inf")])
    ids = []
    for s in inv["sensors"]:
        ids.append(s["sensor_id"])
        lo, hi = s["hard_limits"]
        limits[s["type"]][0] = min(limits[s["type"]][0], lo)
        limits[s["type"]][1] = max(limits[s["type"]][1], hi)
    out = [f"# GENERATED by tools/make_twin_config.py from {path} (inventory {inv.get('version')}). Do not edit by hand.",
           "# Overlay on config.yaml, selected with GUARDIAN_PROFILE=twin.",
           "partners:", '  twin_url: "http://localhost:8000"       # the Twin\'s base URL (their REST + MCP service)',
           "  twin_token_env: TWIN_TOKEN_GUARDIAN      # the guardian-role token the Twin owner gives us",
           "frozen_requires_motion: true               # the Twin simulator holds calm values constant: a constant reading is only frozen when its peers or backup moved",
           "seconds_per_tick: 1.0                      # confirmed by their docs (PLAN_AND_STEPS.md): 1 tick = 1000 ms",
           "polling:", "  mode: twin", "  path: /api/v1/sensors", "  interval_s: 1.0",
           "containment:", "  token_env: TWIN_TOKEN_GUARDIAN", "  paths:",
           "    quarantine_device: /api/v1/isolate", "    isolate_sensor: /api/v1/isolate",
           "    restore_device: /api/v1/restore", "    rollback_reading: null      # the Twin has no rollback tool",
           "adapters:", "  partners:", "    twin:", "      timestamp_source: arrival   # order by seq/tick, stamp on arrival",
           "      field_map: { sensor_id: device_id, zone_id: zone, type: sensor_type, reported_value: value }",
           "      unit_conversions:", "        water_level: { factor: 100, unit: cm, when_unit: m }   # water level is in cm (confirmed by the Twin team); kept only as a safety net for old logs in metres",
           "security:", "  registry:", "    mode: strict", "    allowed_ids:"]
    out += [f"      - {i}" for i in ids]
    out.append("sensor_types:")
    for typ, (lo, hi) in sorted(limits.items()):
        t = TUNING.get(typ, dict(max_rate=hi - lo, frozen_window=8, pair_tol=(hi - lo) / 4))
        out.append(f"  {typ}: {{ min: {lo:g}, max: {hi:g}, max_rate: {t['max_rate']}, expect_noise: true, "
                   f"cross_tol: {t['pair_tol']}, pair_tol: {t['pair_tol']}, frozen_window: {t['frozen_window']}, stale_after_s: null }}")
    print("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
